/** Loot row for a stack of a resource. */
function resLoot(resource: LootEntry['resource'], min: number, max: number, chance = 1): LootEntry {
  return { resource, min, max, chance };
}

/** Loot row for an item drop. */
function itemLoot(item: ItemId, chance: number): LootEntry {
  return { item, chance };
}

