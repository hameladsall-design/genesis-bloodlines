/** Look up an encounter definition. */
export function getEncounter(id: EncounterId): EncounterDef | undefined {
  return ENCOUNTERS.find((enc) => enc.id === id);
}

/** Zone unlocked by winning an encounter (bosses only), if any. */
export function encounterUnlocksZone(id: EncounterId): ZoneId | undefined {
  return ENCOUNTER_EXTRAS[id]?.unlockZone;
}

/** Probability that a victory over this encounter attracts a recruit. */
export function encounterRecruitChance(id: EncounterId): number {
  return ENCOUNTER_EXTRAS[id]?.recruitChance ?? 0;
}

/** All encounters of a given stage, in declaration order. */
export function encountersForStage(stage: number): EncounterDef[] {
  return ENCOUNTERS.filter((enc) => enc.stage === stage);
}

/** Every boss encounter. */
export function bossEncounters(): EncounterDef[] {
  return ENCOUNTERS.filter((enc) => enc.kind === 'boss');
}

/**
 * Encounters the player may take right now: the base level must be high
 * enough, the household must have reached the recommended character level and
 * the encounter's zone must already be unlocked (an empty zone list means no
 * zone gating at all).
 */
export function encountersAvailable(state: GameState): EncounterDef[] {
  const living = state.characterOrder
    .map((id) => state.characters[id])
    .filter((c): c is NonNullable<typeof c> => !!c && c.alive);
  const bestLevel = living.reduce((max, c) => Math.max(max, c.level), 0);
  const zones = state.world?.unlockedZones ?? [];
  return ENCOUNTERS.filter((enc) => {
    if ((enc.minBaseLevel ?? 1) > state.base.level) return false;
    if (enc.minLevel > bestLevel) return false;
    if (enc.zone && zones.length > 0 && !zones.includes(enc.zone)) return false;
    return true;
  });
}

/** Highest character level in the household (helper for the encounter UI). */
export function householdLevel(state: GameState): number {
  let best = 0;
  for (const id of state.characterOrder) {
    const c = state.characters[id];
    if (c && c.alive && c.level > best) best = c.level;
  }
  return best;
}
