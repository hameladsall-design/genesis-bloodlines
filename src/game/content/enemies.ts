/** Shortcut for a full combat stat block. */
function st(over: Partial<CombatStats>): CombatStats {
  return {
    hp: 60,
    damage: 8,
    defense: 3,
    stamina: 40,
    speed: 9,
    accuracy: 0.82,
    evasion: 0.05,
    critChance: 0.04,
    magicResist: 0.05,
    attackRange: 1,
    attackSpeed: 1,
    ...over,
  };
}

/** Shorthand for a resistance row. */
function res(damageType: Resistance['damageType'], resist: number, weakness?: number): Resistance {
  return weakness === undefined
    ? { damageType, resist }
    : { damageType, resist, weakness };
}

