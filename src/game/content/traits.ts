/**
 * Trait catalogue — the genetic vocabulary of GENESIS: BLOODLINES.
 *
 * A trait is a heritable feature expressed by a genotype. Every trait owns one
 * or more loci; a locus is a pair of alleles (`TraitId | 'normal'`).
 *
 * Inheritance modes (see `TraitDef.inheritance`):
 *  - dominant  : expresses when ANY of its loci carries the trait allele.
 *  - recessive : expresses only when ALL of its loci carry the trait allele.
 *  - polygenic : expresses when the count of trait alleles across its loci
 *                reaches `threshold`.
 *
 * Loci are exclusive: a locus belongs to exactly one trait, so an allele
 * placed in `loc.tough` can never be mistaken for the allele of another trait.
 */

