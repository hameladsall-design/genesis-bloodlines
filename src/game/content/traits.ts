/** Every trait id, in declaration order. */
export const TRAIT_IDS: TraitId[] = Object.keys(TRAITS);

/** Every locus used by any trait, de-duplicated and in declaration order. */
export const ALL_LOCI: LocusId[] = Array.from(
  new Set(TRAIT_IDS.flatMap((id) => TRAITS[id]!.loci)),
);

/** The trait that owns a locus (undefined when the locus is unknown). */
export function traitOfLocus(locus: LocusId): TraitDef | undefined {
  return TRAIT_IDS.map((id) => TRAITS[id]!).find((def) => def.loci.includes(locus));
}

/** Looks a trait up by id. */
export function getTrait(id: TraitId): TraitDef | undefined {
  return TRAITS[id];
}
