/**
 * Every skill a race can use at a given level: the innate list plus the race
 * restricted abilities from `SKILLS`. Universal abilities are available to all
 * races and are therefore not listed here.
 */
export function skillsForRace(race: RaceId, level: number): SkillId[] {
  const out = new Set<SkillId>();
  for (const entry of RACE_SKILLS[race] ?? []) {
    if (entry.level <= level) out.add(entry.id);
  }
  for (const skill of SKILL_LIST) {
    if (!skill.races || !skill.races.includes(race)) continue;
    if (skill.unlockLevel > level) continue;
    out.add(skill.id);
  }
  return Array.from(out);
}

/** Localised skill name. */
export function skillName(id: SkillId, lang: 'ar' | 'en' = 'ar'): string {
  const def = getSkill(id);
  if (!def) return id;
  return lang === 'ar' ? def.nameAr : def.nameEn;
}
