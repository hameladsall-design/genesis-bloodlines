/** Every building, keyed by id. */
export const BUILDINGS: Record<BuildingId, BuildingDef> = {};

/** Every building, in catalog order. */
export const BUILDING_LIST: BuildingDef[] = [];

for (const def of DEFS) {
  BUILDINGS[def.id] = def;
  BUILDING_LIST.push(def);
}

/** Default multiplier applied to the build cost of each upgrade step. */
export const DEFAULT_UPGRADE_MULTIPLIERS: number[] = [0, 0.75, 0.6, 0.5, 0.45, 0.4];

/** Look up a building by id. */
export function getBuilding(id: BuildingId): BuildingDef | undefined {
  return BUILDINGS[id];
}

/** Look up a building by id with its extended behaviour fields. */
export function getBuildingDef(id: BuildingId): GameBuildingDef | undefined {
  return BUILDINGS[id] as GameBuildingDef | undefined;
}

/** True when the building may be built at the given base level. */
export function isBuildingUnlockedAt(def: GameBuildingDef, baseLevel: number): boolean {
  if (def.unlockBaseLevel > baseLevel) return false;
  const lvl = getBaseLevel(baseLevel);
  if (lvl.unlocksCategories.includes(def.category)) return true;
  return lvl.unlocksBuildings.includes(def.id);
}

/** Every building available at the given base level. */
export function buildingsUnlockedAt(baseLevel: number): BuildingDef[] {
  return BUILDING_LIST.filter((d) => isBuildingUnlockedAt(d as GameBuildingDef, baseLevel));
}

/** Every building of a given category. */
export function buildingsOfCategory(category: BuildingDef['category']): BuildingDef[] {
  return BUILDING_LIST.filter((d) => d.category === category);
}
