/**
 * GENESIS: BLOODLINES — Building catalog.
 *
 * A data-driven catalog of 64 buildings. Every entry does something DIFFERENT
 * from the others: it houses people, grows food, stores goods, crafts, mines,
 * arms, heals, teaches, trades, defends, or bends the arcane.
 *
 * The public `BUILDINGS` map keeps the shared `BuildingDef` contract from
 * `simulation/types`. The extra per-building behaviour (farm plots, research
 * output, soldier capacity, race affinity...) lives on `GameBuildingDef`, which
 * extends that contract. `getBuildingDef()` returns the extended view.
 */

import type { BuildingDef, BuildingId, RaceId } from '../simulation/types';
import { getBaseLevel } from './baseLevels';

/** Per-building behaviour that goes beyond the shared `BuildingDef` contract. */
export interface GameBuildingDef extends BuildingDef {
  /** True for buildings that behave as a farm plot (plant → grow → harvest). */
  farm?: boolean;
  /** Days a planted farm needs to mature. */
  growDays?: number;
  /** Food yielded by a single harvest. */
  harvestFood?: number;
  /** Multiplier added to EVERY farm's harvest yield. */
  farmYieldBonus?: number;
  /** Extra healing points per day for wounded residents. */
  healing?: number;
  /** True when the building enables the research system. */
  research?: boolean;
  /** Research points produced per day. */
  researchPerDay?: number;
  /** Extra soldier capacity granted to the settlement. */
  soldiers?: number;
  /** Morale contributed to residents. */
  morale?: number;
  /** Coins earned per day. */
  trade?: number;
  /** Race that may build it; undefined = anyone may build it. */
  race?: RaceId;
  /** Reduces the stamina cost of gathering. */
  gatherDiscount?: number;
  /** Reduces the chance of illness (0..1). */
  diseaseResist?: number;
  /** Crafting quality tier of the workshops inside. */
  craftTier?: number;
  /** Reduces settlement unrest. */
  order?: number;
  /** Discount applied when recruiting from the tavern. */
  recruitDiscount?: number;
  /** Resistance against hostile armies. */
  resistance?: number;
}

