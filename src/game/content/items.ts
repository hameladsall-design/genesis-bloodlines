/** Every item as a flat list, ordered by declaration. */
export const ITEM_LIST: ItemDef[] = Object.values(ITEMS);

/** Look up an item definition. */
export function getItem(id: ItemId): ItemDef | undefined {
  return ITEMS[id];
}

/** All items of a given kind (weapons, consumables, materials...). */
export function itemsOfKind(kind: ItemDef['kind']): ItemDef[] {
  return ITEM_LIST.filter((item) => item.kind === kind);
}

/** Localised item name. */
export function itemName(id: ItemId, lang: 'ar' | 'en' = 'ar'): string {
  const def = getItem(id);
  if (!def) return id;
  return lang === 'ar' ? def.nameAr : def.nameEn;
}

/** Total stat bonus granted by a set of items (used by the equipment UI). */
export function combinedItemStats(ids: ItemId[]): Partial<CombatStats> {
  const out: Partial<CombatStats> = {};
  for (const id of ids) {
    const item = getItem(id);
    if (!item?.stats) continue;
    for (const [key, value] of Object.entries(item.stats)) {
      const k = key as keyof CombatStats;
      out[k] = (out[k] ?? 0) + (value ?? 0);
    }
  }
  return out;
}
